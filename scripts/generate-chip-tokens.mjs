#!/usr/bin/env node
/**
 * Generates the **course-area chip palette** into the canonical token layer
 * (`docs/initial-build/visual-design/tokens.css`) and re-copies it to the
 * vendored web copy, keeping `assert:tokens-in-sync` happy (D29).
 *
 * WHY GENERATED (D165/OFC-320). The Book carries 25 course families, each
 * needing {text, fill, border} in two themes — 150 values. Hand-authoring that
 * many pairings is how the old six-family palette ended up shipping with no
 * dark-mode variant for green or red at all: a missing `.dark` override is not
 * "drift", so no guard catches it. Here every family is one hue on a shared
 * ramp, so a family cannot be forgotten and cannot come in under contrast.
 *
 * HOW IT WORKS. Fill, border and text sit at fixed OKLCH lightness/chroma and
 * differ *only* in hue. Because the text-to-fill lightness gap never changes,
 * contrast is constant across the whole palette by construction — the ramp is
 * verified below to clear WCAG AAA (7:1) in both themes, well past the AA 4.5:1
 * the 12px chip label actually requires (D79). Chroma is reduced per-colour
 * where a hue would otherwise fall outside sRGB, which only ever *raises*
 * contrast, so the guarantee holds.
 *
 * WHY THESE HUES. Hue slots are evenly spaced; which family sits in which slot
 * was chosen by minimising the chance that two chips a reader sees together
 * look alike, weighted by how often each family actually occurs in the MITAA
 * alumni data (counts in the table below) and evaluated under normal,
 * deuteranopic and protanomalous vision. That placement pass cut expected
 * collisions ~70% against a naive course-number ordering, and lifted the
 * tightest gap among the six commonest families from 0.0009 to 0.0064 OKLab
 * under deuteranopia — the difference between "identical" and "distinguishable"
 * for the ~8% of an all-male membership with red-green CVD.
 *
 * ⚠ The hue assignment is FROZEN. A brother's chip changing colour between
 * visits is confusing, so re-running this script must be a no-op. Re-deriving
 * the placement is a deliberate decision with a new decision-log entry, not
 * routine maintenance. Colour is never the sole carrier of meaning regardless
 * (D32/D79) — the course code is always in the chip.
 *
 * Usage: node scripts/generate-chip-tokens.mjs [--check]
 *   --check  verify the committed files already match (used by the gate)
 */
import { readFileSync, writeFileSync } from "node:fs";

const CANONICAL = "docs/initial-build/visual-design/tokens.css";
const VENDORED = "apps/web/src/styles/tokens.css";
const BEGIN = "/* >>> generated by scripts/generate-chip-tokens.mjs — do not hand-edit */";
const END = "/* <<< end generated chip palette */";

/** family → hue°, with the MITAA count that drove the placement. Frozen (D165). */
const FAMILIES = [
  ["6", 181.8, 292],
  ["2", 23.4, 120],
  ["15", 138.6, 82],
  ["7", 268.2, 47],
  ["18", 109.8, 47],
  ["16", 52.2, 46],
  ["10", 297.0, 32],
  ["8", 81.0, 29],
  ["14", 354.6, 22],
  ["1", 325.8, 18],
  ["3", 210.6, 15],
  ["21", 239.4, 15],
  ["5", 225.0, 14],
  ["12", 340.2, 14],
  ["9", 311.4, 12],
  ["20", 95.4, 11],
  ["13", 253.8, 9],
  ["4", 153.0, 8],
  ["17", 66.6, 8],
  ["22", 282.6, 8],
  ["24", 124.2, 1],
  ["25", 9.0, 1],
  ["11", 167.4, 0],
  ["19", 37.8, 0],
  ["Other", 196.2, 0],
];

/** Lightness/chroma of each role, per theme. Hue is the only free variable. */
const ROLES = {
  light: { fg: [0.42, 0.1], bg: [0.955, 0.035], border: [0.885, 0.06] },
  dark: { fg: [0.84, 0.09], bg: [0.26, 0.045], border: [0.38, 0.06] },
};

/**
 * The reserved neutral — UNLISTED (D124), and any course code the vocabulary
 * does not know. Deliberately NOT one of the 25 course hues: a course palette
 * change must never move the privacy badge. Hand-picked, from the original
 * visual design's slate.
 */
const NEUTRAL = {
  light: { fg: "#3a4651", bg: "#e9edf0", border: "#d2dadf" },
  dark: { fg: "#c3cbd0", bg: "#1b262b", border: "#2a3940" },
};

const srgb = (v) => (v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);

function oklchToLinear(L, C, H) {
  const h = (H * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  return [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
}

const inGamut = (rgb) => rgb.every((v) => v >= -0.0005 && v <= 1.0005);

/** OKLCH → hex, reducing chroma until the colour fits in sRGB. */
function hex(L, C, H) {
  let c = C;
  let rgb = oklchToLinear(L, c, H);
  while (!inGamut(rgb) && c > 0) {
    c -= 0.002;
    rgb = oklchToLinear(L, c, H);
  }
  return `#${rgb
    .map((v) =>
      Math.round(Math.min(1, Math.max(0, srgb(v))) * 255)
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`;
}

const channels = (h) => [1, 3, 5].map((i) => Number.parseInt(h.slice(i, i + 2), 16) / 255);

function relativeLuminance(h) {
  const [r, g, b] = channels(h).map((v) =>
    v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4,
  );
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(a, b) {
  const [hi, lo] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

// ---------------------------------------------------------------- build

const AA = 4.5;
const worst = { light: Number.POSITIVE_INFINITY, dark: Number.POSITIVE_INFINITY };
const failures = [];

function tokensFor(theme) {
  const lines = [];
  for (const [family, hue, count] of FAMILIES) {
    const role = ROLES[theme];
    const fg = hex(...role.fg, hue);
    const bg = hex(...role.bg, hue);
    const border = hex(...role.border, hue);
    const ratio = contrast(fg, bg);
    worst[theme] = Math.min(worst[theme], ratio);
    if (ratio < AA) {
      failures.push(`${theme} family ${family}: ${ratio.toFixed(2)}:1`);
    }
    const label = count > 0 ? `${count} brothers` : "none recorded";
    // Token keys are lower-cased ("Other" → --chip-other-*); CSS custom properties
    // are case-sensitive, so the one mixed-case family would otherwise be a typo
    // waiting to happen. `familyToken()` in Chips.tsx applies the same rule.
    const key = family.toLowerCase();
    lines.push(
      `  --chip-${key}-fg: ${fg};`,
      `  --chip-${key}-bg: ${bg};`,
      `  --chip-${key}-border: ${border}; /* ${hue.toFixed(1)}° · ${label} · ${ratio.toFixed(2)}:1 */`,
    );
  }
  const n = NEUTRAL[theme];
  const neutralRatio = contrast(n.fg, n.bg);
  worst[theme] = Math.min(worst[theme], neutralRatio);
  lines.push(
    `  --chip-neutral-fg: ${n.fg};`,
    `  --chip-neutral-bg: ${n.bg};`,
    `  --chip-neutral-border: ${n.border}; /* UNLISTED + unknown course · ${neutralRatio.toFixed(2)}:1 */`,
  );
  return lines.join("\n");
}

const light = tokensFor("light");
const dark = tokensFor("dark");

if (failures.length > 0) {
  console.error(
    `\n[chip-tokens] FAIL: pairing below WCAG AA ${AA}:1\n  ${failures.join("\n  ")}\n`,
  );
  process.exit(1);
}

const block = `${BEGIN}
/* ============================================================================
   COURSE-AREA CHIP PALETTE
   ----------------------------------------------------------------------------
   One hue per course family (the leading course number); every code in a family
   shares it, so all nine Course 6 codes wear one colour. Each family = {text,
   fill, border}, at fixed OKLCH lightness/chroma so contrast is uniform:
   worst pairing ${worst.light.toFixed(2)}:1 light, ${worst.dark.toFixed(2)}:1 dark (AA needs 4.5, AAA 7.0).
   Meaning is ALSO carried by the code text — never rely on the colour alone
   (D32/D79). Hue placement is frozen; see the generator's header for why.
   ========================================================================== */
:root {
${light}
}
.dark {
${dark}
}
${END}`;

const source = readFileSync(CANONICAL, "utf8");
const start = source.indexOf(BEGIN);
const stop = source.indexOf(END);
if (start === -1 || stop === -1) {
  console.error(`\n[chip-tokens] FAIL: markers not found in ${CANONICAL}.\n`);
  process.exit(1);
}
const next = source.slice(0, start) + block + source.slice(stop + END.length);

if (process.argv.includes("--check")) {
  const vendored = readFileSync(VENDORED, "utf8");
  if (source !== next || vendored !== next) {
    console.error(
      "\n[chip-tokens] FAIL: the committed chip palette is not what the generator produces.\n" +
        "Regenerate:\n  node scripts/generate-chip-tokens.mjs\n",
    );
    process.exit(1);
  }
  console.log(
    `[chip-tokens] OK: ${FAMILIES.length} families + neutral, worst pairing ` +
      `${worst.light.toFixed(2)}:1 light / ${worst.dark.toFixed(2)}:1 dark.`,
  );
} else {
  writeFileSync(CANONICAL, next);
  writeFileSync(VENDORED, next);
  console.log(
    `[chip-tokens] wrote ${FAMILIES.length} families + neutral to both token copies — ` +
      `worst pairing ${worst.light.toFixed(2)}:1 light / ${worst.dark.toFixed(2)}:1 dark.`,
  );
}
